    class ProcessInput extends Thread {
        ProcessInput(GUIConsole console){
            this.console=console;
        }
        public void run(){
            String goal=console.inputGoal.getText();
            try {
                console.outputState.setText("solving...");
                info=console.engine.solve(goal);
                if (console.engine.isHalted()){
                    exitForm(null);
                } else
                    if (!info.isSuccess()){
                        console.outputSolution.setText("no.");
                        updateSlot(inputGoal.getText(),"no.","");
                        console.outputState.setText("Ready.");
                    } else
                        if (!engine.hasOpenAlternatives()){
                            String binds=info.toString();
                            if (binds.equals("")){
                                console.outputSolution.setText("yes.\nSolution: "+engine.toString(info.getSolution()));
                            } else {
                                console.outputSolution.setText("yes.\n"+binds+"Solution: "+engine.toString(info.getSolution()));
                            }
                            outputState.setText("Ready.");
                            console.updateSlot(console.inputGoal.getText(),"Solution: "+engine.toString(info.getSolution()),binds);
                            console.outputScrollPane.getHorizontalScrollBar().setValue(0);
                            
                        } else {
                            console.outputState.setText("Found a solution (open alternatives can be explored).");
                            String binds=info.toString();
                            console.outputSolution.setText(binds+engine.toString(info.getSolution())+" ?");
                            console.outputScrollPane.getHorizontalScrollBar().setValue(0);
                            console.enableSolutionCmds(true);
                            console.enableGoalCmds(false);
                            console.enableTheoryCmds(false);
                        }
            } catch (MalformedGoalException ex){
                console.outputSolution.setText("syntax error.");
                console.outputState.setText("Ready.");
            } catch (Exception ex){
                console.outputSolution.setText("generic error. "+ex.toString());
                console.outputState.setText("Ready.");
            }
        }
        GUIConsole console;
    }



