  private void inputGoalKeyReleased (java.awt.event.KeyEvent evt) {//GEN-FIRST:event_inputGoalKeyReleased
      int code=evt.getKeyCode();
      // code 38: up arrow
      // code 38: down arrow
      if (code==38){
          // prev in history
          if (historyIndex>0){
              historyIndex--;
          }
          if (historyIndex<history.size()){
              HistoryInfo info=(HistoryInfo)history.get(historyIndex);
              inputGoal.setText(info.goal);
              outputSolution.setText(info.substitution+"\n"+info.solution);
              outputScrollPane.getHorizontalScrollBar().setValue(0);
          } else {
              inputGoal.setText("");
              outputSolution.setText("");
          }
      } else if (code==40){
          // next in history
          if (historyIndex<history.size()){
              historyIndex++;
          }
          if (historyIndex<history.size()){
              HistoryInfo info=(HistoryInfo)history.get(historyIndex);
              inputGoal.setText(info.goal);
              outputSolution.setText(info.substitution+"\n"+info.solution);
              outputScrollPane.getHorizontalScrollBar().setValue(0);
          } else {
              inputGoal.setText("");
              outputSolution.setText("");
          }
      }
  }//GEN-LAST:event_inputGoalKeyReleased

