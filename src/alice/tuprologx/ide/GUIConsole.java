  private void saveTheoryAsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveTheoryAsActionPerformed
      try {
          JFileChooser chooser = new JFileChooser();
          outputState.setText("Save Theory As ...");
          int returnVal = chooser.showOpenDialog(this);
          if(returnVal == JFileChooser.APPROVE_OPTION) {
              theoryFileName=chooser.getCurrentDirectory()+"/"+chooser.getSelectedFile().getName();
              new FileOutputStream(theoryFileName).write(engine.getTheory().toString().getBytes());
              outputState.setText("Save Theory to "+theoryFileName+" ok.");
          }
      } catch (Exception ex){
          outputState.setText("Error saving theory to "+theoryFileName);
      }
  }//GEN-LAST:event_saveTheoryAsActionPerformed

