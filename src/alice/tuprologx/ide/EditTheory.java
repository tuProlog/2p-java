  private void bOkActionPerformed (java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bOkActionPerformed
    // Add your handling code here:
    try {
        Theory th=new Theory(inputTheory.getText());
        editor.engine.setTheory(th);
        editor.setOutputState("New theory accepted.");
        stateBar.setText("Set Theory OK.");
        
        //this.dispose();
        //editor.enableGoalCmds(true);
        //editor.enableTheoryCmds(true);
    } catch (InvalidTheoryException ex){
        //ex.printStackTrace();
        editor.setOutputState("Error setting theory at/before line "+ex.line+".");
        stateBar.setText("Syntax Error at/before line "+ex.line+".");
    } catch (Exception ex){
        ex.printStackTrace();
        editor.setOutputState("Set Theory Failed: Generic Failure.");
        stateBar.setText("Set Theory Failed: Generic Failure.");
    }
  }//GEN-LAST:event_bOkActionPerformed

  private void onWindowsClosing (java.awt.event.WindowEvent evt) {//GEN-FIRST:event_onWindowsClosing
    // Add your handling code here:
    CloseDialog cd=new CloseDialog(new javax.swing.JFrame(), true);
    cd.show();
    boolean closeOk=true;
    if (cd.isTheoryToSet()){
        try {
            Theory th=new Theory(inputTheory.getText());
            editor.engine.setTheory(th);
            editor.setOutputState("New Theory Accepted.");
        } catch (InvalidTheoryException ex){
            editor.setOutputState("Error setting theory at/before line "+ex.line+".");
            closeOk=false;
        } catch (Exception ex){
            editor.setOutputState("Set Theory Failed: Generic Failure.");
            closeOk=false;
        }
    }
    if (closeOk){
        editor.enableGoalCmds(true);
        editor.enableTheoryCmds(true);
        editor.setOutputState("Ready.");
        dispose();
    }
        
  }//GEN-LAST:event_onWindowsClosing


